"""PostgreSQL (Supabase) support for code written against sqlite3.

When DATABASE_URL is set, db.connect() returns a PgConnection from here instead of a sqlite3
connection. It accepts the same SQLite-flavoured SQL the rest of the app already uses, so
features keep being written one way and run on both databases:

    ?                              -> %s
    INSERT OR IGNORE INTO ...      -> INSERT INTO ... ON CONFLICT DO NOTHING
    GROUP_CONCAT(x, sep)           -> string_agg(x, sep)
    datetime('now', 'localtime')   -> to_char(LOCALTIMESTAMP, 'YYYY-MM-DD HH24:MI:SS')
    LIKE                           -> ILIKE (SQLite's LIKE ignores case)
    PRAGMA table_info(t)           -> the same column list from information_schema
    cursor.lastrowid               -> INSERT ... RETURNING id
    sqlite3.IntegrityError         -> still raised, so existing `except` blocks keep working

executescript() also converts the CREATE TABLE schema (INTEGER PRIMARY KEY -> identity column,
REAL -> double precision, COLLATE NOCASE -> citext) and then locks every table against
Supabase's public Data API: the app connects as the database owner, browsers never do.

Rows behave like sqlite3.Row: row["name"], row[0] and dict(row) all work.

Limitation: after a failed statement Postgres refuses further statements in the same
transaction, so code must not catch an IntegrityError and keep using the connection without
rolling back. Every current use raises an ApiError straight away, which rolls back.
"""
import atexit
import decimal
import os
import re
import sqlite3
import threading

_pool = None
_pool_lock = threading.Lock()
_tables_with_id = set()
_id_tables_loaded = False
# Timestamps are written in LVAEP's zone explicitly (`now() AT TIME ZONE ...`) rather than via a
# session `SET TIME ZONE`: Supabase's transaction pooler hands each transaction to a different
# server connection, so session settings don't stick. Only plain zone names are accepted.
TIMEZONE = os.environ.get("LVAEP_TZ", "America/New_York")
if not re.match(r"^[A-Za-z0-9_+./-]+$", TIMEZONE):
    raise ValueError(f"LVAEP_TZ must be a zone name such as America/New_York, not {TIMEZONE!r}")

_LITERAL = re.compile(r"'(?:[^']|'')*'")


def _outside_literals(sql, fn):
    """Apply fn to the parts of sql that are not inside '...' string literals."""
    out, pos = [], 0
    for m in _LITERAL.finditer(sql):
        out.append(fn(sql[pos:m.start()]))
        out.append(m.group(0))
        pos = m.end()
    out.append(fn(sql[pos:]))
    return "".join(out)


def _escape_percent(sql):
    # psycopg treats % as a placeholder marker everywhere, including inside literals.
    return sql.replace("%", "%%")


_NOW_LOCAL = re.compile(r"datetime\(\s*'now'\s*,\s*'localtime'\s*\)", re.I)
_NOW_UTC = re.compile(r"datetime\(\s*'now'\s*\)", re.I)
_DATE_LOCAL = re.compile(r"date\(\s*'now'\s*,\s*'localtime'\s*\)", re.I)
_PRAGMA_TABLE_INFO = re.compile(r"^\s*PRAGMA\s+table_info\(\s*['\"]?(\w+)['\"]?\s*\)\s*;?\s*$", re.I)
_PRAGMA = re.compile(r"^\s*PRAGMA\b", re.I)
_INSERT_OR = re.compile(r"^\s*INSERT\s+OR\s+(IGNORE|REPLACE)\s+INTO\b", re.I)
_INSERT_TABLE = re.compile(r"^\s*INSERT\s+INTO\s+(\w+)", re.I)
_DDL = re.compile(r"^\s*(CREATE|ALTER)\s+TABLE\b", re.I)


def _ddl_types(fragment):
    fragment = re.sub(r"\bid\s+INTEGER\s+PRIMARY\s+KEY\b", "id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
                      fragment, flags=re.I)
    fragment = re.sub(r"\bREAL\b", "DOUBLE PRECISION", fragment, flags=re.I)
    fragment = re.sub(r"\bTEXT\b([^,()]*?)\s+COLLATE\s+NOCASE\b", r"CITEXT\1", fragment, flags=re.I)
    return fragment


def translate(sql):
    """Return (postgres_sql, wants_returning_id) for one SQLite-style statement."""
    m = _PRAGMA_TABLE_INFO.match(sql)
    if m:
        return ("SELECT column_name AS name, data_type AS type FROM information_schema.columns "
                f"WHERE table_schema = current_schema() AND table_name = '{m.group(1).lower()}' "
                "ORDER BY ordinal_position"), False
    if _PRAGMA.match(sql):
        return "SELECT 1 WHERE false", False
    sql = _NOW_LOCAL.sub(f"to_char(now() AT TIME ZONE '{TIMEZONE}', 'YYYY-MM-DD HH24:MI:SS')", sql)
    sql = _NOW_UTC.sub("to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')", sql)
    sql = _DATE_LOCAL.sub(f"to_char((now() AT TIME ZONE '{TIMEZONE}')::date, 'YYYY-MM-DD')", sql)
    ignore = False
    m = _INSERT_OR.match(sql)
    if m:
        if m.group(1).upper() == "REPLACE":
            raise NotImplementedError("INSERT OR REPLACE has no direct Postgres form; use INSERT ... ON CONFLICT")
        sql = sql[:m.start()] + "INSERT INTO" + sql[m.end():]
        ignore = True
    is_ddl = bool(_DDL.match(sql))

    def fix(part):
        part = part.replace("?", "%s")
        part = re.sub(r"\bGROUP_CONCAT\s*\(", "string_agg(", part, flags=re.I)
        part = re.sub(r"\bLIKE\b", "ILIKE", part, flags=re.I)
        return _ddl_types(part) if is_ddl else part

    sql = _outside_literals(_escape_percent(sql), fix)
    sql = sql.rstrip().rstrip(";")
    if ignore:
        sql += " ON CONFLICT DO NOTHING"
    m = _INSERT_TABLE.match(sql)
    wants_id = bool(m) and m.group(1).lower() in _tables_with_id and not re.search(r"\bRETURNING\b", sql, re.I)
    if wants_id:
        sql += " RETURNING id"
    return sql, wants_id


def _split_script(script):
    """Split a script into statements on semicolons outside string literals."""
    parts, buf, pos = [], [], 0
    for m in _LITERAL.finditer(script):
        chunk = script[pos:m.start()]
        pieces = chunk.split(";")
        buf.append(pieces[0])
        for p in pieces[1:]:
            parts.append("".join(buf))
            buf = [p]
        buf.append(m.group(0))
        pos = m.end()
    pieces = script[pos:].split(";")
    buf.append(pieces[0])
    for p in pieces[1:]:
        parts.append("".join(buf))
        buf = [p]
    parts.append("".join(buf))
    return [p.strip() for p in parts if p.strip()]


# ---------- rows ----------

_row_classes = {}


def _row_class(names):
    cls = _row_classes.get(names)
    if cls is None:
        index = {n: i for i, n in enumerate(names)}

        class Row(tuple):
            __slots__ = ()
            _names = names

            def __getitem__(self, key):
                if isinstance(key, str):
                    return tuple.__getitem__(self, index[key])
                return tuple.__getitem__(self, key)

            def keys(self):
                return list(names)

        cls = _row_classes[names] = Row
    return cls


def _plain(value):
    if isinstance(value, decimal.Decimal):
        return int(value) if value == value.to_integral_value() else float(value)
    return value


def _row_factory(cursor):
    if cursor.description is None:
        return lambda values: values
    cls = _row_class(tuple(c.name for c in cursor.description))
    return lambda values: cls(_plain(v) for v in values)


# ---------- connection ----------

# prepare_threshold=None keeps Supabase's connection pooler happy (no server-side prepared statements).
CONNECT_KWARGS = {"autocommit": False, "prepare_threshold": None, "row_factory": _row_factory, "connect_timeout": 15}

# Optional: keep this app's tables in their own schema (tests and shared development projects use
# this so they never touch the live tables in `public`). Needs a session-mode connection (port 5432
# on Supabase): the setting is per connection, and transaction pooling doesn't keep it.
SCHEMA = os.environ.get("LVAEP_PG_SCHEMA", "").strip()
if SCHEMA and not re.match(r"^[a-z_][a-z0-9_]*$", SCHEMA):
    raise ValueError(f"LVAEP_PG_SCHEMA must be a plain lowercase identifier, not {SCHEMA!r}")


def _with_ssl(url):
    """Remote databases get sslmode=require unless the URL says otherwise (psycopg defaults to 'prefer')."""
    from urllib.parse import urlsplit
    if "sslmode=" in url or "://" not in url:
        return url
    host = urlsplit(url).hostname or ""
    if host in ("localhost", "127.0.0.1", "::1", ""):
        return url
    return url + ("&" if "?" in url else "?") + "sslmode=require"


def _ensure_citext(conn):
    """Install the citext extension (case-insensitive text) where it belongs — Supabase keeps extensions
    in its `extensions` schema, which its Data API doesn't expose; plain Postgres uses public — and return
    the schema it lives in."""
    row = conn.execute("SELECT n.nspname FROM pg_extension e JOIN pg_namespace n ON n.oid = e.extnamespace "
                       "WHERE e.extname = 'citext'").fetchone()
    if row:
        return row[0]
    target = "extensions" if conn.execute("SELECT 1 FROM pg_namespace WHERE nspname = 'extensions'").fetchone() else "public"
    conn.execute(f'CREATE EXTENSION IF NOT EXISTS citext WITH SCHEMA "{target}"')
    return target


def _prepare(conn):
    """With LVAEP_PG_SCHEMA set, work in that schema ONLY: `public` is deliberately not on the search path,
    so nothing in an isolated run can read, and nothing can drop, the live tables."""
    if SCHEMA:
        conn.execute(f'CREATE SCHEMA IF NOT EXISTS "{SCHEMA}"')
        ext = _ensure_citext(conn)
        conn.execute(f'SET search_path TO "{SCHEMA}", "{ext}"')
        conn.commit()


def pooled():
    """A long-running server keeps a small connection pool. A serverless function (Vercel) opens one
    connection per request instead: its process may be frozen between requests, which breaks a
    pool's background thread, and the database's own pooler already multiplexes connections.
    LVAEP_PG_POOL=0 forces per-request connections; any other number sets the pool size."""
    setting = os.environ.get("LVAEP_PG_POOL", "").strip()
    if setting:
        return setting != "0"
    return not (os.environ.get("VERCEL") or os.environ.get("LVAEP_SERVERLESS") == "1")


def _get_pool(url):
    global _pool
    with _pool_lock:
        if _pool is None:
            from psycopg_pool import ConnectionPool

            _pool = ConnectionPool(_with_ssl(url), min_size=1, max_size=int(os.environ.get("LVAEP_PG_POOL") or "5"),
                                   open=True, timeout=30, kwargs=CONNECT_KWARGS, configure=_prepare)
            with _pool.connection() as conn:
                _refresh_id_tables(conn)
            atexit.register(close_pool)
        return _pool


def _refresh_id_tables(conn):
    global _id_tables_loaded
    rows = conn.execute(
        "SELECT table_name FROM information_schema.columns WHERE table_schema = current_schema() AND column_name = 'id'"
    ).fetchall()
    _tables_with_id.update(r[0] for r in rows)
    _id_tables_loaded = True


def connect(url):
    if pooled():
        pool = _get_pool(url)
        return PgConnection(pool, pool.getconn())
    import psycopg
    conn = psycopg.connect(_with_ssl(url), **CONNECT_KWARGS)
    _prepare(conn)
    if not _id_tables_loaded:
        _refresh_id_tables(conn)
        conn.commit()
    return PgConnection(None, conn)


def close_pool():
    global _pool
    with _pool_lock:
        if _pool is not None:
            _pool.close()
            _pool = None


class PgCursor:
    def __init__(self, cur, wants_id):
        self._cur = cur
        self.lastrowid = None
        self._buffered = None
        if wants_id and cur.description is not None:
            row = cur.fetchone()
            if row is not None:
                self.lastrowid = row[0]
                self._buffered = [row]

    @property
    def rowcount(self):
        return self._cur.rowcount

    @property
    def description(self):
        return self._cur.description

    def fetchone(self):
        if self._buffered:
            return self._buffered.pop(0)
        return self._cur.fetchone() if self._cur.description is not None else None

    def fetchall(self):
        rows = list(self._buffered or [])
        self._buffered = None
        if self._cur.description is not None:
            rows.extend(self._cur.fetchall())
        return rows

    def __iter__(self):
        return iter(self.fetchall())


class PgConnection:
    """Quacks like sqlite3.Connection for the calls this app makes."""

    row_factory = None  # accepted and ignored: rows always behave like sqlite3.Row

    def __init__(self, pool, conn):
        self._pool, self._conn = pool, conn

    def _run(self, fn):
        import psycopg
        try:
            return fn()
        except psycopg.errors.IntegrityError as e:
            raise sqlite3.IntegrityError(str(e).strip()) from e

    def execute(self, sql, params=()):
        pg_sql, wants_id = translate(sql)
        cur = self._conn.cursor()
        self._run(lambda: cur.execute(pg_sql, tuple(params or ())))
        return PgCursor(cur, wants_id)

    def executemany(self, sql, seq):
        pg_sql, _ = translate(sql)
        cur = self._conn.cursor()
        self._run(lambda: cur.executemany(pg_sql, [tuple(p) for p in seq]))
        return PgCursor(cur, False)

    def executescript(self, script):
        """Run a SQLite schema script. Tables and indexes are converted and created only when missing, and
        new tables are locked against Supabase's Data API. On an up-to-date database this is two cheap
        SELECTs, so a serverless cold start never takes table locks while other requests are running."""
        schema = self._conn.execute("SELECT current_schema()").fetchone()[0]
        have_tables = {r[0] for r in self._conn.execute(
            "SELECT table_name FROM information_schema.tables WHERE table_schema = %s", (schema,)).fetchall()}
        have_indexes = {r[0] for r in self._conn.execute(
            "SELECT indexname FROM pg_indexes WHERE schemaname = %s", (schema,)).fetchall()}
        created, todo = [], []
        for stmt in _split_script(script):
            if _PRAGMA.match(stmt):
                continue
            m = re.match(r"^\s*CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)", stmt, re.I)
            if m:
                if m.group(1).lower() in have_tables:
                    continue
                created.append(m.group(1).lower())
            else:
                mi = re.match(r"^\s*CREATE\s+(?:UNIQUE\s+)?INDEX\s+(?:IF\s+NOT\s+EXISTS\s+)?(\w+)", stmt, re.I)
                if mi and mi.group(1).lower() in have_indexes:
                    continue
            todo.append(stmt)
        if created:
            _ensure_citext(self._conn)
        for stmt in todo:
            pg_sql, _ = translate(stmt)
            self._run(lambda: self._conn.execute(pg_sql, ()))
        if created:
            lock_down(self._conn, schema, created)
            _refresh_id_tables(self._conn)
        self._conn.commit()

    def commit(self):
        self._conn.commit()

    def rollback(self):
        self._conn.rollback()

    def close(self):
        if self._conn is not None:
            try:
                self._conn.rollback()
            finally:
                if self._pool is None:
                    self._conn.close()
                else:
                    self._pool.putconn(self._conn)
                self._conn = None

    def __enter__(self):
        return self

    def __exit__(self, *exc):
        self.close()


def lock_down(conn, schema, tables):
    """Turn on row-level security with no policies, so Supabase's anon/authenticated API keys
    can't read or change these tables. The app connects as the owner, which RLS doesn't restrict."""
    for t in tables:
        conn.execute(f'ALTER TABLE "{schema}"."{t}" ENABLE ROW LEVEL SECURITY')
    conn.execute(
        f"""DO $$ DECLARE r text; BEGIN
             FOREACH r IN ARRAY ARRAY['anon', 'authenticated'] LOOP
               IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = r) THEN
                 EXECUTE format('REVOKE ALL ON ALL TABLES IN SCHEMA %I FROM %I', '{schema}', r);
                 EXECUTE format('REVOKE ALL ON ALL SEQUENCES IN SCHEMA %I FROM %I', '{schema}', r);
               END IF;
             END LOOP; END $$;"""
    )


def drop_tables(conn, tables):
    """Drop the app's tables in the connection's current schema only — names are schema-qualified so an
    unqualified DROP can never resolve through the search path to the live tables in public."""
    schema = conn.execute("SELECT current_schema()").fetchone()[0]
    if SCHEMA and schema != SCHEMA:
        raise RuntimeError(f"Refusing to drop tables: the connection is in schema {schema!r}, not LVAEP_PG_SCHEMA="
                           f"{SCHEMA!r}. Use a session-mode connection (port 5432 on Supabase).")
    existing = {r[0] for r in conn.execute(
        "SELECT table_name FROM information_schema.tables WHERE table_schema = %s", (schema,)).fetchall()}
    for t in tables:
        if t in existing:
            conn.execute(f'DROP TABLE IF EXISTS "{schema}"."{t}" CASCADE')
    conn.commit()
