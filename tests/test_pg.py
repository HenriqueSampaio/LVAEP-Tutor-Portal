"""The SQLite -> Postgres translation in app/pg.py (no database needed).

The full API suite also runs against Postgres when DATABASE_URL is set; see the README.
"""
import unittest

from app import pg


class TranslateTest(unittest.TestCase):

    def setUp(self):
        pg._tables_with_id.update({"users", "notifications"})

    def t(self, sql):
        return pg.translate(sql)[0]

    def test_placeholders_and_percent(self):
        self.assertEqual(self.t("SELECT * FROM users WHERE name = ? AND note = 'why?' AND x LIKE '5%'"),
                         "SELECT * FROM users WHERE name = %s AND note = 'why?' AND x ILIKE '5%%'")

    def test_insert_or_ignore_and_returning_id(self):
        self.assertEqual(self.t("INSERT OR IGNORE INTO settings (key, value) VALUES (?, ?)"),
                         "INSERT INTO settings (key, value) VALUES (%s, %s) ON CONFLICT DO NOTHING")
        sql, wants_id = pg.translate("INSERT INTO users (name) VALUES (?)")
        self.assertEqual((sql, wants_id), ("INSERT INTO users (name) VALUES (%s) RETURNING id", True))
        self.assertFalse(pg.translate("INSERT INTO settings (key) VALUES (?)")[1])

    def test_functions(self):
        self.assertEqual(self.t("SELECT GROUP_CONCAT(u.name, ', ') FROM users u"),
                         "SELECT string_agg(u.name, ', ') FROM users u")
        self.assertIn("to_char(LOCALTIMESTAMP", self.t("UPDATE x SET at = datetime('now', 'localtime')"))

    def test_schema(self):
        ddl = self.t("CREATE TABLE IF NOT EXISTS users (id INTEGER PRIMARY KEY, email TEXT NOT NULL UNIQUE COLLATE NOCASE, "
                     "hours REAL NOT NULL DEFAULT 0, created_at TEXT NOT NULL DEFAULT (datetime('now', 'localtime')))")
        self.assertIn("id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", ddl)
        self.assertIn("email CITEXT NOT NULL UNIQUE", ddl)
        self.assertIn("hours DOUBLE PRECISION", ddl)
        self.assertNotIn("datetime(", ddl)

    def test_pragma(self):
        self.assertIn("information_schema.columns", self.t("PRAGMA table_info(reports)"))
        self.assertIn("'reports'", self.t("PRAGMA table_info(reports)"))
        self.assertEqual(self.t("PRAGMA foreign_keys = ON"), "SELECT 1 WHERE false")

    def test_script_splitting_keeps_semicolons_in_strings(self):
        self.assertEqual(pg._split_script("CREATE TABLE a (x TEXT DEFAULT ';'); CREATE INDEX i ON a (x);"),
                         ["CREATE TABLE a (x TEXT DEFAULT ';')", "CREATE INDEX i ON a (x)"])

    def test_rows_behave_like_sqlite_rows(self):
        Row = pg._row_class(("id", "name"))
        r = Row((1, "Ana"))
        self.assertEqual((r["name"], r[0], dict(r)), ("Ana", 1, {"id": 1, "name": "Ana"}))


if __name__ == "__main__":
    unittest.main()
